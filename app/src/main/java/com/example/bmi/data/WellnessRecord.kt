package com.example.bmi.data

/*
 * ============================================================================
 * WellnessRecord.kt —— 健康日志里的一条记录（纯数据类）
 * ============================================================================
 * 【这个文件是干什么的】
 *   把“某一天的健康记录”打包成一个对象，方便在 Activity 和数据库之间传递。
 *   它只有四个字段：日期、身体状况、步数、备注，没有任何业务逻辑。
 *
 * 【字段设计（考试时最先想清楚这一步）】
 *   date      日期字符串 "yyyy-MM-dd"，同时是数据库主键 → 同一天只保留最新一条；
 *   condition 身体状况，用 0/1/2 表示（0=良好，1=一般，2=较差），
 *             刚好对应 Spinner 的 selectedItemPosition，省掉一次转换；
 *   steps     当天步数（整数）；
 *   note      备注，可以为空字符串，但不要用 null（数据库列设了 NOT NULL）。
 *
 * ────────────────────────────────────────────────────────────────────────────
 * 【依赖关系】
 *   本文件依赖：无。
 *   谁依赖本文件：WellnessDbHelper、MainActivity、HistoryActivity。
 * ────────────────────────────────────────────────────────────────────────────
 */
data class WellnessRecord(
    val date: String,
    val condition: Int,
    val steps: Int,
    val note: String
)
